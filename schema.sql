-- ==============================================================================
-- ERP Mayorista - Aberturas Miño: Estructura Completa
-- Módulos: Inventario (Productos), Clientes y Pedidos (Compra / Venta)
-- ==============================================================================

-- 1. TABLA PRODUCTOS
create table if not exists public.productos (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  descripcion text not null,
  cantidad integer not null default 0,
  precio_venta numeric(12, 2) not null default 0.00,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

do $$
begin
  if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'productos' and column_name = 'precio_venta') then
    alter table public.productos add column precio_venta numeric(12, 2) not null default 0.00;
  end if;
  if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'productos' and column_name = 'codigo') then
    alter table public.productos add column codigo text not null default '';
  end if;
  if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'productos' and column_name = 'descripcion') then
    alter table public.productos add column descripcion text not null default '';
  end if;
  if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'productos' and column_name = 'cantidad') then
    alter table public.productos add column cantidad integer not null default 0;
  end if;
end $$;

-- 2. TABLA CLIENTES
create table if not exists public.clientes (
  id bigint generated by default as identity primary key,
  razon_social text not null,
  cuit text not null,
  telefono text,
  direccion text,
  email text,
  condicion_iva text not null default 'Responsable Inscripto',
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create index if not exists idx_clientes_cuit on public.clientes(cuit);
create index if not exists idx_clientes_razon_social on public.clientes(razon_social);

-- 3. TABLA PEDIDOS (Cabecera)
create table if not exists public.pedidos (
  id bigint generated by default as identity primary key,
  cliente_id bigint not null references public.clientes(id) on delete restrict,
  tipo text not null check (tipo in ('COMPRA', 'VENTA')),
  estado text not null default 'COMPLETADO' check (estado in ('PENDIENTE', 'COMPLETADO', 'CANCELADO')),
  subtotal numeric(14, 2) not null default 0.00,
  incluye_iva boolean not null default false,
  monto_iva numeric(14, 2) not null default 0.00,
  total_pedido numeric(14, 2) not null default 0.00,
  notas text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Migración segura de columnas en pedidos
do $$
begin
  if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'pedidos' and column_name = 'subtotal') then
    alter table public.pedidos add column subtotal numeric(14, 2) not null default 0.00;
  end if;
  if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'pedidos' and column_name = 'incluye_iva') then
    alter table public.pedidos add column incluye_iva boolean not null default false;
  end if;
  if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'pedidos' and column_name = 'monto_iva') then
    alter table public.pedidos add column monto_iva numeric(14, 2) not null default 0.00;
  end if;
end $$;

create index if not exists idx_pedidos_cliente on public.pedidos(cliente_id);
create index if not exists idx_pedidos_tipo on public.pedidos(tipo);
create index if not exists idx_pedidos_estado on public.pedidos(estado);

-- 4. TABLA PEDIDOS_DETALLE (Líneas dinámicas del pedido)
create table if not exists public.pedidos_detalle (
  id bigint generated by default as identity primary key,
  pedido_id bigint not null references public.pedidos(id) on delete cascade,
  producto_id bigint not null references public.productos(id) on delete restrict,
  cantidad integer not null check (cantidad > 0),
  precio_unitario numeric(12, 2) not null check (precio_unitario >= 0),
  subtotal numeric(14, 2) not null check (subtotal >= 0),
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create index if not exists idx_pedidos_detalle_pedido on public.pedidos_detalle(pedido_id);
create index if not exists idx_pedidos_detalle_producto on public.pedidos_detalle(producto_id);

-- 5. HABILITAR ROW LEVEL SECURITY (RLS)
alter table public.productos enable row level security;
alter table public.clientes enable row level security;
alter table public.pedidos enable row level security;
alter table public.pedidos_detalle enable row level security;

