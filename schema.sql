-- 2. TABLA CONFIGURACION
create table if not exists public.configuracion (
  id bigint generated by default as identity primary key,
  clave text not null unique,
  valor numeric(14, 2) not null default 0.00
);

insert into public.configuracion (clave, valor)
values ('precio_kilo_aluminio', 7000)
on conflict (clave) do nothing;

-- 3. TABLA CLIENTES
create table if not exists public.clientes (
  id bigint generated by default as identity primary key,
  razon_social text not null,
  cuit text not null,
  telefono text,
  direccion text,
  email text,
  condicion_iva text not null default 'Responsable Inscripto',
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 4. TABLA PEDIDOS (Cabecera)
create table if not exists public.pedidos (
  id uuid default gen_random_uuid() primary key,
  cliente_id bigint not null references public.clientes(id) on delete restrict,
  tipo text not null check (tipo in ('COMPRA', 'VENTA')),
  estado text not null default 'COMPLETADO' check (estado in ('PENDIENTE', 'PRESUPUESTO', 'COMPLETADO', 'CANCELADO')),
  subtotal numeric(14, 2) not null default 0.00,
  incluye_iva boolean not null default false,
  monto_iva numeric(14, 2) not null default 0.00,
  total_pedido numeric(14, 2) not null default 0.00,
  notas text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table public.pedidos drop constraint if exists pedidos_estado_check;
alter table public.pedidos add constraint pedidos_estado_check
  check (estado in ('PENDIENTE', 'PRESUPUESTO', 'COMPLETADO', 'CANCELADO'));

-- 5. TABLA PEDIDOS_DETALLE
create table if not exists public.pedidos_detalle (
  id bigint generated by default as identity primary key,
  pedido_id uuid not null references public.pedidos(id) on delete cascade,
  producto_id uuid references public.productos(id) on delete restrict,
  material text,
  peso_kg numeric(10, 3),
  cantidad integer not null default 1 check (cantidad > 0),
  precio_unitario numeric(12, 2) not null check (precio_unitario >= 0),
  subtotal numeric(14, 2) not null check (subtotal >= 0),
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 6. ROW LEVEL SECURITY (RLS)
alter table public.productos enable row level security;
alter table public.configuracion enable row level security;
alter table public.clientes enable row level security;
alter table public.pedidos enable row level security;
alter table public.pedidos_detalle enable row level security;
