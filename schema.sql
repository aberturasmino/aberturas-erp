insert into public.productos (codigo, descripcion, cantidad, unidad_medida, precio_venta)
values
  ('ALU-A30', 'Aluminio Línea A30 New - Extrusión por Kilo', 250.000, 'KG', 7000.00),
  ('ALU-MODENA', 'Aluminio Línea Módena - Extrusión por Kilo', 320.000, 'KG', 7000.00),
  ('ALU-HERRERO', 'Aluminio Línea Herrero - Extrusión por Kilo', 180.000, 'KG', 7000.00)
