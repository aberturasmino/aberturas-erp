-- ==============================================================================
-- ERP Mayorista - Aberturas Miño: Estructura Estricta de Remitos de Perfiles
-- Columnas obligatorias: codigo, descripcion, cantidad
-- ==============================================================================

-- 1. Crear tabla si no existe
create table if not exists public.productos (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  descripcion text not null,
  cantidad integer not null default 0,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. Migración ALTER TABLE para tablas existentes
do $$
begin
  -- Migrar codigo_sku a codigo si existe
  if exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'productos' and column_name = 'codigo_sku') then
    alter table public.productos rename column codigo_sku to codigo;
  end if;

  -- Migrar nombre a descripcion si existe
  if exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'productos' and column_name = 'nombre') then
    alter table public.productos rename column nombre to descripcion;
  end if;

  -- Migrar stock_actual a cantidad si existe
  if exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'productos' and column_name = 'stock_actual') then
    alter table public.productos rename column stock_actual to cantidad;
  end if;

  -- Asegurar que las columnas existan
  if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'productos' and column_name = 'codigo') then
    alter table public.productos add column codigo text not null default '';
  end if;
  if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'productos' and column_name = 'descripcion') then
    alter table public.productos add column descripcion text not null default '';
  end if;
  if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'productos' and column_name = 'cantidad') then
    alter table public.productos add column cantidad integer not null default 0;
  end if;

  -- Eliminar columnas anteriores que ya no aplican a perfiles
  if exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'productos' and column_name = 'linea') then
    alter table public.productos drop column linea;
  end if;
  if exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'productos' and column_name = 'tipo') then
    alter table public.productos drop column tipo;
  end if;
  if exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'productos' and column_name = 'precio_mayorista') then
    alter table public.productos drop column precio_mayorista;
  end if;
end $$;

-- 3. Políticas de acceso (RLS)
alter table public.productos enable row level security;

drop policy if exists "Permitir lectura publica" on public.productos;
create policy "Permitir lectura publica" on public.productos for select using (true);

drop policy if exists "Permitir actualizacion cantidad" on public.productos;
create policy "Permitir actualizacion cantidad" on public.productos for update using (true) with check (true);

drop policy if exists "Permitir insercion" on public.productos;
create policy "Permitir insercion" on public.productos for insert with check (true);

drop policy if exists "Permitir eliminacion" on public.productos;
create policy "Permitir eliminacion" on public.productos for delete using (true);
