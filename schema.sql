-- 1. Asegurar tabla productos y agregar columna precio_venta
create table if not exists public.productos (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  descripcion text not null,
  cantidad integer not null default 0,
  precio_venta numeric(12, 2) not null default 0.00,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

do $$
begin
  -- Migración de columnas de productos
  if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'productos' and column_name = 'precio_venta') then
    alter table public.productos add column precio_venta numeric(12, 2) not null default 0.00;
  end if;
  if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'productos' and column_name = 'codigo') then
    alter table public.productos add column codigo text not null default '';
  end if;
  if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'productos' and column_name = 'descripcion') then
    alter table public.productos add column descripcion text not null default '';
  end if;
  if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'productos' and column_name = 'cantidad') then
    alter table public.productos add column cantidad integer not null default 0;
  end if;
end $$;

-- 2. Crear tabla de clientes
create table if not exists public.clientes (
  id bigint generated by default as identity primary key,
  razon_social text not null,
  cuit text not null,
  telefono text,
  direccion text,
  email text,
  condicion_iva text not null default 'Responsable Inscripto',
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Índices para búsquedas ágiles
create index if not exists idx_clientes_cuit on public.clientes(cuit);
create index if not exists idx_clientes_razon_social on public.clientes(razon_social);

-- 3. Habilitar Row Level Security (RLS) en productos y clientes
alter table public.productos enable row level security;
alter table public.clientes enable row level security;

-- Políticas para productos
drop policy if exists "Permitir lectura productos" on public.productos;
create policy "Permitir lectura productos" on public.productos for select using (true);

drop policy if exists "Permitir gestion productos" on public.productos;
create policy "Permitir gestion productos" on public.productos for all using (true) with check (true);

-- Políticas RLS para clientes (usuarios autenticados y acceso seguro)
drop policy if exists "Permitir lectura clientes a usuarios autenticados" on public.clientes;
create policy "Permitir lectura clientes a usuarios autenticados"
  on public.clientes for select
  to authenticated
  using (true);

drop policy if exists "Permitir insercion clientes a usuarios autenticados" on public.clientes;
create policy "Permitir insercion clientes a usuarios autenticados"
  on public.clientes for insert
  to authenticated
  with check (true);

drop policy if exists "Permitir actualizacion clientes a usuarios autenticados" on public.clientes;
create policy "Permitir actualizacion clientes a usuarios autenticados"
  on public.clientes for update
  to authenticated
  using (true)
  with check (true);

drop policy if exists "Permitir eliminacion clientes a usuarios autenticados" on public.clientes;
create policy "Permitir eliminacion clientes a usuarios autenticados"
  on public.clientes for delete
  to authenticated
  using (true);

-- Política complementaria para entorno demo o peticiones directas
drop policy if exists "Permitir acceso publico controlado clientes" on public.clientes;
create policy "Permitir acceso publico controlado clientes"
  on public.clientes for all
  using (true)
  with check (true);
