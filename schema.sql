-- ==============================================================================
-- ERP Mayorista - Aberturas Miño: Estructura Sincronizada con Supabase
-- Módulos: Inventario (UNIDADES / KG), Clientes, Cotizador y Pedidos
-- ==============================================================================

-- 1. TABLA PRODUCTOS (soporta UNIDADES y KG con cantidad numeric(12, 3))
create table if not exists public.productos (
  id uuid default gen_random_uuid() primary key,
  codigo text not null unique,
  descripcion text not null,
  cantidad numeric(12, 3) not null default 0.000,
  unidad_medida text not null default 'UNIDADES' check (unidad_medida in ('UNIDADES', 'KG')),
  precio_venta numeric(12, 2) not null default 0.00,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table public.productos
  add column if not exists unidad_medida text not null default 'UNIDADES';

alter table public.productos drop constraint if exists productos_unidad_medida_check;
alter table public.productos add constraint productos_unidad_medida_check
  check (unidad_medida in ('UNIDADES', 'KG'));

