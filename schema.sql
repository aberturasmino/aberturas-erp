-- ==============================================================================
-- ERP Mayorista - Aberturas Miño: Esquema de Base de Datos para Supabase
-- Tabla: productos (campos: id, codigo_sku, nombre, linea, tipo, precio_mayorista, stock_actual)
-- ==============================================================================

-- 1. Crear la tabla de productos
create table if not exists public.productos (
  id bigint generated by default as identity primary key,
  codigo_sku text not null unique,
  nombre text not null,
  linea text not null,
  tipo text not null,
  precio_mayorista numeric(12, 2) not null default 0.00,
  stock_actual integer not null default 0,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. Habilitar Row Level Security (RLS)
alter table public.productos enable row level security;

-- 3. Políticas de acceso (lectura y actualización permitidas para el MVP del ERP)
create policy "Permitir lectura publica de productos"
  on public.productos for select
  using (true);

create policy "Permitir actualizacion de stock"
  on public.productos for update
  using (true)
  with check (true);

create policy "Permitir insercion de productos"
  on public.productos for insert
  with check (true);

